#!/usr/bin/env python3
"""Componere indicem operum ad publicum, integritate fontium servata.

Curator indicem operum solum e fontibus publice admissis generat.
Haec ratio formas typographicas corrigit; numquam argumenta ex
exemplaribus manu scriptis in locum indicis probati substituit.
"""

from __future__ import annotations

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CV_PROJECTS_PATH = ROOT / "cv" / "current_projects_public.tex"

SOURCE_MARKER = "% Auto-generated by scripts/stem_cv_curator.py."
RESEARCH_HEADING = r"\section*{Research Experience}"
DEFAULT_LIST = r"\begin{itemize}"
POLISHED_LIST = (
    r"\begin{itemize}"
    r"[leftmargin=1.75em,labelsep=0.45em,topsep=1pt,itemsep=0pt,parsep=0pt]"
)


def main() -> int:
    source = CV_PROJECTS_PATH.read_text(encoding="utf-8")
    if not source.startswith(SOURCE_MARKER + "\n"):
        raise SystemExit("Missing evidence-filtered public CV generator marker.")
    if RESEARCH_HEADING not in source:
        raise SystemExit("Missing generated Research Experience section.")
    if r"\cvrole{" not in source:
        raise SystemExit("Generated public CV has no evidenced project entries.")

    polished = re.sub(re.escape(DEFAULT_LIST) + r"(?!\[)", lambda _: POLISHED_LIST, source)
    CV_PROJECTS_PATH.write_text(polished, encoding="utf-8")
    print("Polished evidence-filtered public CV sections without replacing project claims.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
